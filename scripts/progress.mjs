// Renders docs/PROGRESS.md from docs/requirements.json + docs/progress.meta.json,
// and enforces SPEC section 11: every Done row names a test that exists and a commit.
// Usage: node scripts/progress.mjs [--check]
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const reqs = JSON.parse(readFileSync(join(root, "docs/requirements.json"), "utf8"));
const meta = JSON.parse(readFileSync(join(root, "docs/progress.meta.json"), "utf8"));
const check = process.argv.includes("--check");

const SKIP = new Set(["node_modules", ".dart_tool", ".next", "build", ".git", "Pods"]);
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP.has(name)) continue;
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) walk(p, out);
    else if (/\.(dart|ts|tsx|mjs|sql|yml|yaml)$/.test(name) && /(test|spec)|\/tests\/|\.github\/workflows/.test(p)) out.push(p);
  }
  return out;
}
const corpus = walk(root).map((f) => readFileSync(f, "utf8")).join("\n");

const problems = [];
for (const r of reqs) {
  if (!["Done", "Partial", "Not started"].includes(r.status)) problems.push(`${r.id}: bad status ${r.status}`);
  if (r.status === "Done") {
    if (!r.test) problems.push(`${r.id}: Done without a proving test`);
    else if (!corpus.includes(r.test.replace(/ ?\(.*$/, ""))) problems.push(`${r.id}: test not found in repo: "${r.test}"`);
    if (!r.commit) problems.push(`${r.id}: Done without a commit`);
  }
}

const count = (s) => reqs.filter((r) => r.status === s).length;
const phases = [...new Set(reqs.map((r) => r.phase))];
const list = (a) => (a.length ? a.map((x) => `- ${x}`).join("\n") : "- None");

const md = `# Progress

Generated by \`npm run progress\` from \`docs/requirements.json\` and \`docs/progress.meta.json\`. Edit those, not this file.

**${reqs.length} requirements:** ${count("Done")} Done, ${count("Partial")} Partial, ${count("Not started")} Not started.

## Checklist

${phases
  .map((ph) => {
    const rows = reqs.filter((r) => r.phase === ph);
    const head = ph === "Before submission" ? "Before submission" : `Phase ${ph}`;
    return `### ${head}\n\n| ID | Requirement | Status | Proving test | Commit |\n|---|---|---|---|---|\n${rows
      .map((r) => `| ${r.id} | ${r.title} | ${r.status} | ${r.test ? "\`" + r.test + "\`" : ""} | ${r.commit} |`)
      .join("\n")}`;
  })
  .join("\n\n")}

## Mocked or stubbed

${list(meta.mocked.map((m) => `**${m.name}** (${m.ids}): ${m.reason}. Replace with: ${m.needs}.`))}

## Needs real-device or real-key check

${list(meta.realDevice)}

## Commands

${meta.commands.map(([k, v]) => `**${k}**\n\n\`\`\`sh\n${v}\n\`\`\``).join("\n\n")}

## Design notes per screen (PSY-16)

${list(meta.psy16.map((p) => `**${p.screen}**: shaped by ${p.principle}. Unlike a generic app because ${p.unlike}`))}

## Notes

${list(meta.notes)}

## Blockers and decisions needed from Felix

${list(meta.blockers)}
`;

const out = join(root, "docs/PROGRESS.md");
if (check) {
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  if (!existsSync(out) || readFileSync(out, "utf8") !== md) {
    console.error("docs/PROGRESS.md is stale. Run: npm run progress");
    process.exit(1);
  }
  console.log("progress: ok");
} else {
  if (problems.length) console.error("warnings:\n" + problems.join("\n"));
  writeFileSync(out, md);
  console.log(`wrote docs/PROGRESS.md (${count("Done")}/${reqs.length} Done)`);
  void execSync;
}
